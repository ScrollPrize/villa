export function viewerElements(document) {
  const elements = {};
  for (const [name, selector] of Object.entries(SELECTORS)) {
    elements[name] = document.querySelector(selector);
    if (elements[name] === null) throw new Error(`index.html has no ${selector} for elements.${name}.`);
  }
  elements.surfacePlaneInputs = document.querySelectorAll("[data-surface-plane]");
  elements.openSourceButtons = document.querySelectorAll("#open-source-button, [data-open-source]");
  return elements;
}
