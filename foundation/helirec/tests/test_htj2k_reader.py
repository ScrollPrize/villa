"""Seekable float32 HDF5 reads, without a Blosc/HDF5 codec plugin.

Fixtures are generated by reference/htj2k/generate.cpp with pinned OpenJPH 0.32.0.
The reversible fixture has an independent integer-wavelet oracle; the lossy
fixture exercises the signed-32-bit 9/7 path used by Paris4.
"""
from pathlib import Path
import struct

import numpy as np
import pytest

from helirec import _core
from test_calibration import _low_band_53

h5py = pytest.importorskip("h5py")
ROWS, COLS = 257, 259
DATA = Path(__file__).parent / "reference" / "htj2k"
ZERO = np.zeros(1, np.int32)
pytestmark = pytest.mark.skipif(not _core.htj2k_float_frames_supported(), reason="HELIREC_OPENJPH=OFF")


def _chunk(stream, rows=ROWS, cols=COLS, constant=False, sample_bytes=4):
    # One Blosc2 frame, one chunk, one block, with a B2JPF32 v1 wrapper.
    lo, hi = (-0.5, -0.5) if constant else (-0.5, 1.5)
    wrapper = struct.pack("<8sHHBBHQddddQ", b"B2JPF32\0", 1, 64, 32, 0,
                          4 if constant else 0, len(stream), lo, hi, lo, hi, 0)
    payload = wrapper + stream if sample_bytes == 4 else stream
    out = bytearray(62 + 40 + len(payload))
    out[2:9] = b"b2frame"
    struct.pack_into(">I", out, 11, 62)
    out[62:66] = bytes([5, 1, 6 << 5, sample_bytes])
    struct.pack_into("<III", out, 66, rows * cols * sample_bytes, rows * cols * sample_bytes, 40 + len(payload))
    out[62 + 22] = 40
    struct.pack_into("<II", out, 62 + 32, 36, len(payload))
    out[102:] = payload
    return out


def _write(path, chunk, rows=ROWS, cols=COLS, frames=1, chunk_rows=None, dtype="float32"):
    with h5py.File(path, "w") as f:
        dcpl = h5py.h5p.create(h5py.h5p.DATASET_CREATE)
        cr = rows if chunk_rows is None else chunk_rows
        dcpl.set_chunk((1, cr, cols))
        dcpl.set_filter(32026, h5py.h5z.FLAG_OPTIONAL, ())
        dt = h5py.h5t.IEEE_F32LE if dtype == "float32" else h5py.h5t.STD_U16LE
        d = h5py.h5d.create(f.id, b"data", dt,
                           h5py.h5s.create_simple((frames, rows, cols)), dcpl)
        for k in range(frames):
            for row in range(0, rows, cr):
                d.write_direct_chunk((k, row, 0), bytes(chunk))


def _reader(path, reduce=0, selective=True, rows=ROWS, cols=COLS):
    return _core.RawReader([str(path)], "data", rows, cols, reduce=reduce,
                           dtype="float32", selective=selective)


def _samples(rows=ROWS, cols=COLS, unsigned=False):
    state = 17
    a = np.empty((rows, cols), np.int64)
    for i in range(a.size):
        state = (1664525 * state + 1013904223) & 0xffffffff
        a.flat[i] = 20000 + (state >> 17) if unsigned else (state >> 6) - (1 << 25)
    return a


@pytest.mark.parametrize("wavelet", ["53", "97"])
def test_resolutions_and_selective_io(tmp_path, wavelet):
    path = tmp_path / "float.h5"
    stream = (DATA / f"signed32_{wavelet}.j2k").read_bytes()
    _write(path, _chunk(stream))
    want = _samples()
    for r in range(4):
        rd = _reader(path, r)
        full = _reader(path, r, selective=False)
        got = rd.read_frames(ZERO, ZERO, n_threads=1)
        baseline = full.read_frames(ZERO, ZERO, n_threads=1)
        assert got.dtype == np.float32 and rd.dtype == "float32"
        assert got.shape == (1, (ROWS + (1 << r) - 1) >> r, (COLS + (1 << r) - 1) >> r)
        np.testing.assert_array_equal(got, baseline)
        if r == 3:
            assert rd.bytes_read < full.bytes_read
            assert rd.bytes_read <= 65536 + 512
        if wavelet == "53":
            ref = (-0.5 + (want + (1 << 31)) * (2.0 / 0xffffffff)).astype(np.float32)
            np.testing.assert_array_equal(got[0], ref)
            want = _low_band_53(_low_band_53(want.T).T)
        # Row windows, padding, repeated cache hits and background prefetch.
        rd.set_cache_bytes(4 << 20)
        rd.set_prefetch_threads(2)
        rd.prefetch_rows(ZERO, ZERO, ZERO, 4)
        for row in (-2, 3, rd.rows - 2, rd.rows + 1):
            piece = rd.read_rows(ZERO, ZERO, np.array([row], np.int32), 5)
            ref = np.zeros_like(piece)
            a, b = max(0, row), min(rd.rows, row + 5)
            if b > a:
                ref[:, a-row:b-row] = got[:, a:b]
            np.testing.assert_array_equal(piece, ref)
        before = rd.bytes_read
        rd.read_frames(ZERO, ZERO)
        assert rd.bytes_read == before
        rd.set_prefetch_threads(0)


def test_constant_and_plain_float(tmp_path):
    path = tmp_path / "constant.h5"
    _write(path, _chunk(b"", constant=True))
    for r in range(4):
        rd = _reader(path, r)
        np.testing.assert_array_equal(rd.read_frames(ZERO, ZERO), np.full((1, rd.rows, rd.cols), -0.5, np.float32))
        assert rd.bytes_read < 1024
    a = _samples().astype(np.float32)[None]
    for chunks in (None, (1, ROWS, COLS)):
        with h5py.File(path, "w") as f:
            f.create_dataset("data", data=a, chunks=chunks)
        np.testing.assert_array_equal(_reader(path).read_frames(ZERO, ZERO), a)
        with pytest.raises(Exception, match="JPEG 2000 only"):
            _reader(path, 1).read_frames(ZERO, ZERO)


def test_chunk_boundaries_and_errors(tmp_path):
    path = tmp_path / "multi.h5"
    chunk = _chunk((DATA / "signed32_53.j2k").read_bytes())
    _write(path, chunk, rows=2 * ROWS, frames=2, chunk_rows=ROWS)
    rd = _reader(path, rows=2 * ROWS)
    whole = rd.read_frames(np.zeros(2, np.int32), np.array([1, 0], np.int32), n_threads=2)
    part = rd.read_rows(np.zeros(2, np.int32), np.array([1, 0], np.int32), np.full(2, ROWS-2, np.int32), 5, n_threads=2)
    np.testing.assert_array_equal(part, whole[:, ROWS-2:ROWS+3])
    with pytest.raises(Exception, match="chunks of"):
        _reader(path, 1, rows=2 * ROWS).read_frames(ZERO, ZERO)
    with pytest.raises(Exception, match="dataset is not uint16"):
        _core.RawReader([str(path)], "data", 2 * ROWS, COLS).read_frames(ZERO, ZERO)
    with pytest.raises(Exception, match="dtype"):
        _core.RawReader([], "data", 1, 1, dtype="float64")
    with pytest.raises(Exception, match="nrows"):
        rd.read_rows(ZERO, ZERO, ZERO, -1)


@pytest.mark.parametrize("offset,replacement", [
    (11, struct.pack(">I", 0xffffffff)),  # frame header beyond chunk
    (62+4, struct.pack("<I", 1)),        # wrong uncompressed size
    (62+32, struct.pack("<I", 0xffffffff)),  # block beyond chunk
    (102+8, b"\x02\x00"),              # unsupported float wrapper version
    (102+16, struct.pack("<Q", 0xffffffffffffffff)),  # huge payload
    (102+24, struct.pack("<d", float("nan"))),
    (102+12, b"\x10"),                 # wrapper/codestream precision mismatch
])
def test_malformed_container(tmp_path, offset, replacement):
    chunk = _chunk((DATA / "signed32_53.j2k").read_bytes())
    chunk[offset:offset+len(replacement)] = replacement
    path = tmp_path / "bad.h5"
    _write(path, chunk)
    with pytest.raises(Exception, match="compressed frame chunk"):
        _reader(path, 3).read_frames(ZERO, ZERO, n_threads=1)


@pytest.mark.parametrize("wavelet", ["53", "97"])
def test_uint16_selective_io(tmp_path, wavelet):
    path = tmp_path / "uint16.h5"
    _write(path, _chunk((DATA / f"unsigned16_{wavelet}.j2k").read_bytes(), 256, 256, sample_bytes=2),
           rows=512, cols=256, chunk_rows=256, dtype="uint16")
    want = _samples(256, 256, unsigned=True)
    for r in range(4):
        rd = _core.RawReader([str(path)], "data", 512, 256, reduce=r, decoder="openjph")
        full = _core.RawReader([str(path)], "data", 512, 256, reduce=r, decoder="openjph", selective=False)
        got = rd.read_frames(ZERO, ZERO, n_threads=2)
        np.testing.assert_array_equal(got, full.read_frames(ZERO, ZERO, n_threads=2))
        if r == 3:
            assert rd.bytes_read < full.bytes_read / 2
        if wavelet == "53":
            np.testing.assert_array_equal(got[0], np.tile(want, (2, 1)))
            want = _low_band_53(_low_band_53(want.T).T)
        storage = rd.storage()
        assert storage["chunk_rows"] == 256 and storage["codec"] == "JPEG 2000 (HTJ2K)"
        assert storage["reversible"] == (wavelet == "53")
    with pytest.raises(Exception, match="decoder"):
        _core.RawReader([], "data", 256, 256, decoder="unsupported")
